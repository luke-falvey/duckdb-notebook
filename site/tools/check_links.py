"""Checks every internal link and image in the built site, including those MkDocs does not see
(raw HTML in pages, the theme). Run after `mkdocs build`:

    python3 site/tools/check_links.py [build/site]
"""
import html.parser
import os
import sys
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


class Page(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.links, self.ids = [], set()

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if "id" in attrs:
            self.ids.add(attrs["id"])
        for key in ("href", "src"):
            if attrs.get(key) and tag in ("a", "img", "link", "script"):
                self.links.append(attrs[key])


def target(site, page, link):
    url = urllib.parse.urlparse(link)
    if url.scheme or link.startswith("//") or link.startswith("mailto:"):
        return None, None
    path = urllib.parse.unquote(url.path)
    if not path:
        resolved = page
    elif path.startswith("/"):
        resolved = os.path.join(site, path.lstrip("/"))
    else:
        resolved = os.path.normpath(os.path.join(os.path.dirname(page), path))
    if os.path.isdir(resolved):
        resolved = os.path.join(resolved, "index.html")
    return resolved, url.fragment


def main():
    site = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "site"))
    pages = {}
    for folder, _, files in os.walk(site):
        for name in files:
            # Exports are generated by the extension and self-contained; 404.html uses site-absolute URLs.
            if name.endswith(".html") and not (folder.endswith("examples") and name != "index.html") and name != "404.html":
                path = os.path.join(folder, name)
                parser = Page()
                with open(path, encoding="utf-8") as f:
                    parser.feed(f.read())
                pages[path] = parser
    broken = []
    for path, parser in pages.items():
        for link in parser.links:
            resolved, fragment = target(site, path, link)
            if resolved is None:
                continue
            if not os.path.exists(resolved):
                broken.append("%s: %s (no such file)" % (os.path.relpath(path, site), link))
            elif fragment and resolved in pages and fragment not in pages[resolved].ids:
                broken.append("%s: %s (no such anchor)" % (os.path.relpath(path, site), link))
    for line in broken:
        print(line)
    print("%d pages checked, %d broken links" % (len(pages), len(broken)))
    sys.exit(1 if broken else 0)


if __name__ == "__main__":
    main()
